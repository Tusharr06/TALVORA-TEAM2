"""Ports and Data Transfer Objects for Deterministic Scheduling and Slot Solving."""

from dataclasses import dataclass, field
from datetime import datetime
from uuid import UUID

from talvora.modules.integrations.application.ports import (
    CalendarSchedule,
    TimeInterval,
)


@dataclass(frozen=True)
class CandidateSlot:
    """A proposed deterministic interview slot in UTC."""

    start_utc: datetime
    end_utc: datetime
    interviewer_membership_ids: list[UUID]


@dataclass(frozen=True)
class SolverInput:
    """Complete constraint parameters passed into DeterministicSlotSolver."""

    request_id: UUID
    duration_minutes: int
    buffer_before_minutes: int
    buffer_after_minutes: int
    minimum_lead_time_hours: int
    working_hours_start: int
    working_hours_end: int
    working_days: list[int]
    timezone: str
    target_date_start: datetime
    target_date_end: datetime
    candidate_intervals: list[TimeInterval]
    interviewer_schedules: dict[UUID, CalendarSchedule]
    internal_reservations: list[TimeInterval] = field(default_factory=list)
    evaluation_time: datetime | None = None
    step_minutes: int = 15
    max_proposals: int = 5


@dataclass(frozen=True)
class SolverResult:
    """Deterministic result generated by the slot solver."""

    proposed_slots: list[CandidateSlot]
    unknown_interviewers: list[UUID]
    total_slots_evaluated: int
    is_fully_available: bool
